package com.knowledgeassistant.genai;

import com.knowledgeassistant.genai.dto.GenAiAnswerRequest;
import com.knowledgeassistant.genai.dto.GenAiAnswerResponse;
import com.knowledgeassistant.genai.dto.GenAiIngestResponse;
import com.knowledgeassistant.genai.dto.GenAiTurn;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.slf4j.MDC;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.http.HttpStatus;
import org.springframework.http.client.SimpleClientHttpRequestFactory;
import org.springframework.stereotype.Component;
import org.springframework.web.client.ResourceAccessException;
import org.springframework.core.io.Resource;
import org.springframework.http.MediaType;
import org.springframework.util.LinkedMultiValueMap;
import org.springframework.util.MultiValueMap;
import org.springframework.web.client.RestClient;
import org.springframework.web.client.RestClientResponseException;

import java.util.List;
import java.util.UUID;

/**
 * The only thing in Spring that talks to the GenAI service.
 *
 * <p><strong>Hand-written against the FastAPI spec, and nothing checks it</strong> —
 * BACKLOG.md 3a. The Python side generates its OpenAPI document from the same Pydantic
 * models that validate its requests, so that side cannot drift from itself. This side can.
 * Until the client is generated from {@code /openapi.json} or a test asserts against it,
 * {@link GenAiContractException} is the alarm rather than the prevention.
 */
@Component
public class GenAiClient {

    private static final Logger log = LoggerFactory.getLogger(GenAiClient.class);

    private final RestClient restClient;
    private final GenAiProperties properties;

    // @Autowired is required now that a second constructor exists: with two candidates and
    // no annotation Spring finds no default constructor and every context fails to start.
    // Caught by the full suite, not by running the new test alone — that one boots no
    // context, so it could not have noticed.
    @Autowired
    public GenAiClient(GenAiProperties properties) {
        this(properties, RestClient.builder().requestFactory(timeoutsFrom(properties)));
    }

    /** The timeouts, applied where a test's mock transport will not be clobbered by them. */
    private static SimpleClientHttpRequestFactory timeoutsFrom(GenAiProperties properties) {
        SimpleClientHttpRequestFactory factory = new SimpleClientHttpRequestFactory();
        factory.setConnectTimeout(properties.connectTimeout());
        factory.setReadTimeout(properties.timeout());
        return factory;
    }

    /**
     * Takes the builder so a test can observe what reaches the wire.
     *
     * <p>Added on Day 18 for a specific reason worth recording: the first version of
     * {@code TraceIdPropagationTest} could not reach the real client, so it rebuilt the
     * interceptor inside the test and asserted against its own copy. That test would have
     * passed with the production interceptor deleted — a test of a duplicate, which is the
     * failure this project keeps finding in other forms.
     *
     * <p>Widening one constructor is the smaller cost. Spring still uses the single-argument
     * form; nothing else calls this one but the test.
     */
    GenAiClient(GenAiProperties properties, RestClient.Builder builder) {
        this.properties = properties;
        // The request factory is NOT set here, deliberately. It belongs to the public
        // constructor: MockRestServiceServer installs its own transport on the builder, and
        // setting one here would overwrite it — which is exactly what made the first version
        // of TraceIdPropagationTest attempt real HTTP and see no request at all.
        this.restClient = builder
                .baseUrl(properties.baseUrl())
                // PROPAGATE THE TRACE ID. Day 18, and it was a defect the GenAI service had
                // been reporting on every single request:
                //
                //     app.trace — no X-Trace-Id header on /answer — caller should propagate it
                //
                // TraceIdFilter has stamped every Spring log line with a traceId since Month
                // 2 and exposed it to the browser, but this client never forwarded it. So a
                // question produced TWO unrelated trace ids — one in Spring's logs, another
                // generated by the GenAI service — and no single grep could follow a request
                // from the browser through retrieval and generation. Which is precisely the
                // thing "diagnose a poor AI answer" needs.
                //
                // An interceptor rather than a header on each call: it covers /answer and
                // /ingest and anything added later, and cannot be forgotten at a new call
                // site. MDC is thread-local and this client is called on the request thread,
                // so the value is the one the filter set.
                .requestInterceptor((request, body, execution) -> {
                    String traceId = MDC.get("traceId");
                    if (traceId != null) {
                        request.getHeaders().add("X-Trace-Id", traceId);
                    }
                    return execution.execute(request, body);
                })
                .build();
    }

    /**
     * Ask for a grounded answer.
     *
     * <p>{@code allowedDocumentIds} is passed through <strong>unconditionally</strong>,
     * including when it is empty. There is no "skip the call if the list is empty"
     * short-circuit, even though it would save a round trip: that is the same {@code if}
     * that, on the Python side, would turn an empty allow-list into a search across every
     * user's documents. The call costs ~37ms when the list is empty because the service
     * returns {@code insufficient_context} without ever loading the model.
     */
    public GenAiAnswerResponse answer(String question, List<UUID> allowedDocumentIds, UUID sessionId,
                                      List<GenAiTurn> history, String model) {
        GenAiAnswerRequest request = new GenAiAnswerRequest(
                question, allowedDocumentIds, properties.topK(), properties.minScore(), sessionId,
                history == null ? List.of() : history, model);

        long started = System.currentTimeMillis();
        GenAiAnswerResponse response = postWithOneRetry(request);
        long elapsed = System.currentTimeMillis() - started;

        if (response.trace() != null) {
            // The trace, never the answer text and never the dropped quotes: both can carry
            // document content, and LogRedactionTest exists to keep that out of the log.
            log.info("genai answer in {}ms: outcome={} citations={} template={} completion_tokens={} "
                            + "candidates={} collapsed={} dropped_quotes={} trace_id={}",
                    elapsed, response.outcome(),
                    response.citations() == null ? 0 : response.citations().size(),
                    response.trace().promptTemplateVersion(), response.trace().completionTokens(),
                    response.trace().candidatesBeforeThreshold(), response.trace().collapsedDuplicates(),
                    response.trace().droppedQuotes() == null ? 0 : response.trace().droppedQuotes().size(),
                    response.trace().traceId());
        }
        return response;
    }

    /**
     * One retry, and only for failures that cost nothing to have attempted.
     *
     * <p>Connection refused and {@code 503 MODEL_NOT_READY} both mean the service is not ready
     * to work yet — the first fails in microseconds, the second in milliseconds, and either can
     * resolve on its own while models finish loading.
     *
     * <p><strong>A timeout is never retried.</strong> The first attempt already spent up to 90
     * seconds and may still be generating on the other side; a second would make one slow
     * request into a three-minute one. Neither is a 5xx after generation started — that is a bug
     * in Python, and running it again produces the same bug more slowly.
     */
    private GenAiAnswerResponse postWithOneRetry(GenAiAnswerRequest request) {
        try {
            return post(request);
        } catch (GenAiUnavailableException first) {
            if (!first.isWorthRetrying()) {
                throw first;
            }
            log.warn("genai unavailable ({}), retrying once", first.getMessage());
            try {
                Thread.sleep(500);
            } catch (InterruptedException interrupted) {
                Thread.currentThread().interrupt();
                throw first;
            }
            return post(request);
        }
    }

    /**
     * The `detail.message` from the service's error envelope, or null.
     *
     * <p>Parsed leniently on purpose: a malformed error body must not turn a 503 into a
     * crash while reporting a 503. Falling back to the generic wording is always safe.
     */
    private String messageFrom(String body) {
        try {
            com.fasterxml.jackson.databind.JsonNode detail =
                    new com.fasterxml.jackson.databind.ObjectMapper().readTree(body).path("detail");
            String message = detail.path("message").asText(null);
            return (message == null || message.isBlank()) ? null : message;
        } catch (Exception unparseable) {
            return null;
        }
    }

    /**
     * Send a document's bytes for extraction, chunking and embedding. Day 16.
     *
     * <p><strong>This is the second outbound call this client makes, and the first that is
     * not a question.</strong> Until today the only thing Spring asked the GenAI service for
     * was an answer; a document's chunks were loaded by a benchmark fixture script that
     * documents its own rule violation, so the product's ingestion path had never run.
     *
     * <p>Multipart because the service takes bytes and never reads a filesystem — the two
     * processes do not share one, and making them share one would put document storage in
     * two places.
     *
     * <p><strong>Not retried.</strong> {@link #answer} retries once because a question is
     * cheap, idempotent and worth another shot. Ingestion is neither cheap nor obviously
     * idempotent from here, and a failure leaves the document {@code failed} where a human
     * can re-upload it. Retrying a 60-second embed on a timeout doubles the wait before
     * telling the user anything.
     *
     * @throws GenAiUnavailableException the service is unreachable, still loading its model,
     *                                   or could not extract text from the file
     */
    public GenAiIngestResponse ingest(UUID documentId, String filename, String contentType,
                                      Resource bytes) {
        MultiValueMap<String, Object> form = new LinkedMultiValueMap<>();
        form.add("file", bytes);
        form.add("document_id", documentId.toString());
        form.add("filename", filename);
        form.add("content_type", contentType);

        long started = System.currentTimeMillis();
        try {
            GenAiIngestResponse response = restClient.post()
                    .uri("/ingest")
                    .contentType(MediaType.MULTIPART_FORM_DATA)
                    .body(form)
                    .retrieve()
                    .body(GenAiIngestResponse.class);

            if (response == null) {
                throw new GenAiContractException("POST /ingest returned an empty body");
            }
            // The count is checked against the list rather than trusted. A truncated response
            // would otherwise be written as a short but complete-looking document, which is
            // the confident-wrong-signal failure this project keeps finding: no error
            // anywhere, and the document answers questions about only its first half.
            int actual = response.chunks() == null ? 0 : response.chunks().size();
            if (actual != response.chunkCount()) {
                throw new GenAiContractException(
                        "POST /ingest said " + response.chunkCount() + " chunks and sent " + actual);
            }
            log.info("genai.ingest documentId={} chunks={} dim={} elapsedMs={} trace={}",
                    documentId, actual, response.embeddingDim(),
                    System.currentTimeMillis() - started,
                    response.trace() == null ? null : response.trace().traceId());
            return response;

        } catch (ResourceAccessException transportFailure) {
            boolean timedOut = transportFailure.getCause() instanceof java.net.SocketTimeoutException;
            if (timedOut) {
                log.error("genai /ingest exceeded the {}s timeout for documentId={}",
                        properties.timeout().toSeconds(), documentId);
                throw GenAiUnavailableException.timedOut(properties.timeout().toSeconds());
            }
            log.error("genai unreachable at {} for /ingest", properties.baseUrl(), transportFailure);
            throw GenAiUnavailableException.unreachable();

        } catch (RestClientResponseException httpError) {
            // 415 and 422 are the FILE's fault, not the service's, and the message is written
            // for a person: "No readable text could be extracted. A scanned PDF needs OCR."
            // Relaying it is safe — it is a system string, never document text.
            String reason = messageFrom(httpError.getResponseBodyAsString());
            log.warn("genai /ingest refused documentId={} status={} reason={}",
                    documentId, httpError.getStatusCode().value(), reason);
            // `because` rather than a new factory: Day 13 added it for exactly this shape
            // — a reason the service gave for itself, which must not be overwritten with a
            // generic one. It is also correctly marked not-worth-retrying.
            throw GenAiUnavailableException.because(
                    reason == null ? "The document could not be processed." : reason);
        }
    }

    private GenAiAnswerResponse post(GenAiAnswerRequest request) {
        try {
            return restClient.post()
                    .uri("/answer")
                    .body(request)
                    .retrieve()
                    .body(GenAiAnswerResponse.class);

        } catch (ResourceAccessException transportFailure) {
            // Connection refused AND read timeout both land here. They are told apart by
            // cause, because they need different handling: one is worth retrying and the
            // other has already cost the user 90 seconds.
            boolean timedOut = transportFailure.getCause() instanceof java.net.SocketTimeoutException;
            if (timedOut) {
                log.error("genai exceeded the {}s timeout", properties.timeout().toSeconds());
                throw GenAiUnavailableException.timedOut(properties.timeout().toSeconds());
            }
            log.error("genai unreachable at {}", properties.baseUrl(), transportFailure);
            throw GenAiUnavailableException.unreachable();

        } catch (RestClientResponseException httpError) {
            HttpStatus status = HttpStatus.resolve(httpError.getStatusCode().value());

            if (status == HttpStatus.SERVICE_UNAVAILABLE) {
                // Pass the service's OWN message through rather than substituting one.
                //
                // This used to answer every 503 with "the AI is still starting up" — true on
                // Day 8, when a model loading at boot was the only reason for a 503. Day 13
                // added a second: a cloud model out of quota, which looks identical on the
                // wire and means the opposite. A user waited four times for a model that was
                // already loaded, because the error told them to.
                //
                // The message is a system string, never document text, so relaying it leaks
                // nothing.
                String reason = messageFrom(httpError.getResponseBodyAsString());
                log.warn("genai unavailable: {}", reason);
                throw GenAiUnavailableException.because(reason);
            }
            if (status == HttpStatus.UNPROCESSABLE_ENTITY) {
                // OUR bug, not the user's. The frontend never reaches that service and
                // Spring validated the input before calling, so a 422 means this client
                // and the spec disagree. Logged with the field detail Python returns,
                // which names paths and never values.
                log.error("genai rejected our request as malformed — this is a Spring defect: {}",
                        httpError.getResponseBodyAsString());
                throw new GenAiContractException("GenAI rejected a malformed request from Spring");
            }
            log.error("genai returned {}: {}", httpError.getStatusCode(), httpError.getResponseBodyAsString());
            throw new GenAiContractException("GenAI service error: " + httpError.getStatusCode());
        }
    }
}
